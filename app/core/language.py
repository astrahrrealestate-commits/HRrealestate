def detect_language(text: str) -> Language:
    """`nl` or `en` when one language has more function words; `unknown` when none or a tie (numbers, emoji, names)."""
    words = _WORDS.findall(text.lower())
    nl = sum(w in _DUTCH for w in words)
    en = sum(w in _ENGLISH for w in words)
    if nl > en:
        return "nl"
    if en > nl:
        return "en"
    return "unknown"
